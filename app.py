@app.errorhandler(429)
def handle_rate_limit(_error):
    if request.path == "/login":
        return (
            render_template(
                "login.html",
                title="MyFXJournal | Login",
                body_class="auth-layout",
                error="Too many sign-in attempts. Please wait a minute and try again.",
            ),
            429,
        )
    wants_json = (
        request.path.startswith("/api/")
        or request.path.startswith("/dashboard/weekly-review/")
        or request.path == "/pricing/waitlist"
    )
    if not wants_json and (request.accept_mimetypes.best or "") == "application/json":
        wants_json = True
    if wants_json:
        return (
            jsonify(
                {
                    "error": "Too many requests. Please try again later.",
                    "ok": False,
                }
            ),
            429,
        )
    return "Too many requests. Please try again later.", 429


def request_wants_json_response():
    if request.is_json:
        return True
    if request.headers.get("X-Requested-With") == "XMLHttpRequest":
        return True
    if (
        request.path.startswith("/api/")
        or request.path.startswith("/dashboard/weekly-review/")
        or request.path.startswith("/dashboard/journal/")
        or request.path == "/dashboard/journal/sessions"
        or request.path == "/pricing/waitlist"
    ):
        return True
    return (request.accept_mimetypes.best or "") == "application/json"


@app.errorhandler(CSRFError)
def handle_csrf_error(error):
    message = error.description or "Your session expired. Please refresh and try again."
    if request_wants_json_response():
        return jsonify({"error": "csrf_failed", "message": message}), 400
    flash(message, "error")
    return render_error_page(
        400,
        "Request could not be verified",
        message,
        title="MyFXJournal | 400",
    )


def render_error_page(status_code, heading, description, title=None):
    user_logged_in = bool(session.get("user_id"))
    primary_endpoint = "dashboard.home" if user_logged_in else "login"
    primary_label = "Back to Dashboard" if user_logged_in else "Go to Login"
    secondary_endpoint = "trades.trades" if user_logged_in else None
    secondary_label = "View Trades" if user_logged_in else None
    return (
        render_template(
            "error.html",
            title=title or f"MyFXJournal | {status_code}",
            status_code=status_code,
            heading=heading,
            description=description,
            primary_url=url_for(primary_endpoint),
            primary_label=primary_label,
            secondary_url=url_for(secondary_endpoint) if secondary_endpoint else None,
            secondary_label=secondary_label,
            request_path=request.path,
        ),
        status_code,
    )


@app.errorhandler(HTTPException)
def handle_http_error(error):
    if request_wants_json_response():
        return (
            jsonify(
                {
                    "error": error.name or "request_error",
                    "message": error.description or "Something went wrong while processing your request.",
                }
            ),
            error.code or 500,
        )
    page_content = {
        403: (
            "Access denied",
            "You do not have permission to view this page.",
            "MyFXJournal | 403",
        ),
        404: (
            "Page not found",
            "The page you requested does not exist or may have moved.",
            "MyFXJournal | 404",
        ),
        405: (
            "Method not allowed",
            "That action is not available for this page.",
            "MyFXJournal | 405",
        ),
    }
    heading, description, title = page_content.get(
        error.code,
        (
            error.name or "Request error",
            error.description or "Something went wrong while processing your request.",
            f"MyFXJournal | {error.code}" if error.code else "MyFXJournal | Error",
        ),
    )
    return render_error_page(error.code or 500, heading, description, title=title)


